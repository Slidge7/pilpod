//! Per-browser tab slots and command queue shared by the browser detector and
//! the localhost HTTP bridge.

use std::{
    collections::hash_map::DefaultHasher,
    collections::HashMap,
    hash::{Hash, Hasher},
    sync::{Arc, Mutex},
    time::Instant,
};

use crate::browser_bridge::connections::push_ws_command;
use crate::browser_bridge::WsConnectionMap;
use serde::Serialize;

use crate::browser_dto::{BrowserTab, TabMedia};

/// Latest tab state pushed by one browser profile (keyed by `browserId` UUID).
#[derive(Debug, Clone)]
pub struct BrowserSlot {
    pub last_seen: Instant,
    /// Stable UUID generated by the extension and stored in `chrome.storage.local`.
    pub browser_id: String,
    /// Human-readable browser name sent by the extension (e.g. "Chrome", "Brave").
    pub browser_name: String,
    /// Catalog id verified via the connection's owning process (peer-PID match).
    /// `None` when the lookup failed — fall back to the self-reported name.
    pub verified_os_id: Option<String>,
    /// All open tabs in this browser — each with an optional `media` field.
    pub tabs: Vec<BrowserTab>,
    /// Hash of tab content for diff-before-emit; excludes `last_seen`.
    pub content_hash: u64,
}

impl BrowserSlot {
    /// Catalog id for this slot: PID-verified truth first, self-report fallback.
    pub fn effective_os_id(&self) -> String {
        self.verified_os_id
            .clone()
            .unwrap_or_else(|| crate::browser_catalog::browser_name_to_id(&self.browser_name))
    }
}

/// Key: `browserId` UUID sent by the extension.
pub type BrowserSlotsMap = Arc<Mutex<HashMap<String, BrowserSlot>>>;

/// Commands the desktop app queues for a browser profile; the companion extension
/// receives them in the JSON body of its next POST to `/browser-tabs`.
/// Outer key: `browserId` UUID. Inner key: `tabId` — latest command per tab wins.
pub type BrowserCommandsQueue = Arc<Mutex<HashMap<String, HashMap<i32, BrowserMediaCommand>>>>;

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BrowserMediaCommand {
    pub tab_id: i32,
    /// `playPause`, `next`, `previous`, `focusTab`, `reactivateTab`, `reloadTab`, `closeTab`,
    /// `seek`, `setTabVolume`, `muteTab`, `pip`
    pub action: String,
    /// Optional numeric parameter for commands that need it (e.g. seek position in seconds,
    /// volume as 0–600 percentage).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub value: Option<f64>,
    /// Timestamp of when the command was enqueued; used to drop stale entries.
    #[serde(skip)]
    pub enqueued_at: Instant,
}

pub fn enqueue_browser_command(
    queue: &BrowserCommandsQueue,
    ws_connections: Option<&WsConnectionMap>,
    browser_id: &str,
    tab_id: i32,
    action: &str,
    value: Option<f64>,
) {
    let cmd = BrowserMediaCommand {
        tab_id,
        action: action.to_string(),
        value,
        enqueued_at: Instant::now(),
    };

    if let Some(ws) = ws_connections {
        if push_ws_command(ws, browser_id, &cmd) {
            return;
        }
    }

    if let Ok(mut q) = queue.lock() {
        q.entry(browser_id.to_string())
            .or_default()
            .insert(tab_id, cmd);
    }
}

fn hash_str(h: &mut DefaultHasher, s: &str) {
    s.hash(h);
}

/// Idle time is bucketed before hashing. The UI renders it rounded to whole
/// minutes and only reacts at the 5-minute mark, so millisecond precision here
/// buys nothing and costs an emit on every frame.
const IDLE_BUCKET_MS: u64 = 30_000;

/// Whole-second bucket for a float time value.
///
/// Hashing the raw `f64` bits made the tab hash change on *every* progress
/// frame the extension sends (5 Hz, per the protocol's `progressHz`). That
/// defeated the diff-before-emit guard in `apply_ingest`, so `browsers://update`
/// fired five times a second for the entire time any media was playing.
/// One bucket per second is all the UI can display.
///
/// NaN and negatives collapse to `0` rather than hashing as distinct values.
fn secs_bucket(v: f64) -> i64 {
    if v.is_finite() && v > 0.0 {
        v as i64
    } else {
        0
    }
}

fn hash_media(h: &mut DefaultHasher, media: &TabMedia) {
    hash_str(h, &media.playback_state);
    hash_str(h, &media.title);
    hash_str(h, &media.artist);
    hash_str(h, &media.album);
    hash_str(h, &media.artwork_url);
    secs_bucket(media.duration).hash(h);
    secs_bucket(media.current_time).hash(h);
    media.page_visible.hash(h);
    (media.user_idle_ms / IDLE_BUCKET_MS).hash(h);
    hash_str(h, &media.document_state);
    media.tab_volume.to_bits().hash(h);
    media.tab_muted.hash(h);
    media.can_seek.hash(h);
    media.can_pip.hash(h);
    media.can_next.hash(h);
    media.can_prev.hash(h);
    media.in_pip.hash(h);
}

fn hash_tab(h: &mut DefaultHasher, tab: &BrowserTab) {
    tab.tab_id.hash(h);
    tab.window_id.hash(h);
    hash_str(h, &tab.url);
    hash_str(h, &tab.title);
    hash_str(h, &tab.favicon_url);
    hash_str(h, &tab.tab_state);
    tab.active.hash(h);
    tab.window_focused.hash(h);
    tab.audible.hash(h);
    tab.muted.hash(h);
    tab.pinned.hash(h);
    tab.index.hash(h);
    match &tab.media {
        None => 0u8.hash(h),
        Some(m) => {
            1u8.hash(h);
            hash_media(h, m);
        }
    }
}

/// Stable hash over tab list content for diff-before-emit.
pub fn hash_tabs(tabs: &[BrowserTab]) -> u64 {
    let mut hasher = DefaultHasher::new();
    tabs.len().hash(&mut hasher);
    for tab in tabs {
        hash_tab(&mut hasher, tab);
    }
    hasher.finish()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample_tab(title: &str) -> BrowserTab {
        BrowserTab {
            tab_id: 1,
            window_id: 2,
            url: "https://example.com".into(),
            title: title.into(),
            favicon_url: String::new(),
            tab_state: "active".into(),
            active: true,
            window_focused: true,
            audible: false,
            muted: false,
            pinned: false,
            index: 0,
            media: None,
            browser_id: "test-browser".into(),
        }
    }

    #[test]
    fn enqueue_dedupes_per_tab() {
        let q: BrowserCommandsQueue = Arc::new(Mutex::new(HashMap::new()));
        enqueue_browser_command(&q, None, "b1", 10, "next", None);
        enqueue_browser_command(&q, None, "b1", 10, "playPause", None);
        enqueue_browser_command(&q, None, "b1", 11, "previous", None);
        enqueue_browser_command(&q, None, "b2", 20, "playPause", None);
        let g = q.lock().expect("lock");
        assert_eq!(g["b1"].len(), 2);
        assert_eq!(g["b1"][&10].action, "playPause");
        assert_eq!(g["b1"][&11].action, "previous");
        assert_eq!(g["b2"][&20].tab_id, 20);
    }

    #[test]
    fn hash_tabs_stable_for_same_input() {
        let tabs = vec![sample_tab("Hello")];
        assert_eq!(hash_tabs(&tabs), hash_tabs(&tabs));
    }

    #[test]
    fn hash_tabs_changes_when_title_changes() {
        let a = vec![sample_tab("Hello")];
        let b = vec![sample_tab("World")];
        assert_ne!(hash_tabs(&a), hash_tabs(&b));
    }

    /// All `TabMedia` fields carry serde defaults, so this is the cheapest way
    /// to build one without a `Default` impl the production code never needs.
    fn tab_with_media(current_time: f64, user_idle_ms: u64) -> BrowserTab {
        let mut tab = sample_tab("Playing");
        let mut media: TabMedia = serde_json::from_str("{}").expect("default media");
        media.playback_state = "playing".into();
        media.duration = 240.0;
        media.current_time = current_time;
        media.user_idle_ms = user_idle_ms;
        tab.media = Some(media);
        tab
    }

    #[test]
    fn hash_ignores_sub_second_progress() {
        // The extension streams progress at 5 Hz. Two frames inside the same
        // second must hash identically, or `apply_ingest` emits on every one.
        let a = vec![tab_with_media(12.0, 0)];
        let b = vec![tab_with_media(12.8, 0)];
        assert_eq!(hash_tabs(&a), hash_tabs(&b));
    }

    #[test]
    fn hash_still_tracks_whole_seconds() {
        let a = vec![tab_with_media(12.0, 0)];
        let b = vec![tab_with_media(13.0, 0)];
        assert_ne!(hash_tabs(&a), hash_tabs(&b));
    }

    #[test]
    fn hash_ignores_idle_jitter_below_bucket() {
        // Idle ticks up continuously; the UI shows whole minutes and only reacts
        // at 5 minutes, so anything under the bucket must not force an emit.
        let a = vec![tab_with_media(12.0, 1_000)];
        let b = vec![tab_with_media(12.0, 20_000)];
        assert_eq!(hash_tabs(&a), hash_tabs(&b));
    }

    #[test]
    fn hash_tracks_idle_across_buckets() {
        let a = vec![tab_with_media(12.0, 10_000)];
        let b = vec![tab_with_media(12.0, 90_000)];
        assert_ne!(hash_tabs(&a), hash_tabs(&b));
    }

    #[test]
    fn secs_bucket_collapses_nan_and_negatives() {
        assert_eq!(secs_bucket(f64::NAN), 0);
        assert_eq!(secs_bucket(f64::INFINITY), 0);
        assert_eq!(secs_bucket(-5.0), 0);
        assert_eq!(secs_bucket(0.0), 0);
        assert_eq!(secs_bucket(7.9), 7);
    }
}
